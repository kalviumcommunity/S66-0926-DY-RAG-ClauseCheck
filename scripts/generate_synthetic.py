#!/usr/bin/env python
"""Generate synthetic price schedules (DOCX) and compliance certificates (TXT).

Everything comes from `random.Random(seed)`, so the same seed gives identical text, manifest
rows and ground truth. The facts written to `ground_truth.jsonl` become the exact-value eval
questions.
"""

import argparse
import csv
import datetime as dt
import hashlib
import io
import json
import random
import sys
import zipfile
from pathlib import Path

import docx

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from clausecheck.core import schema  # noqa: E402
from clausecheck.core.ids import doc_id  # noqa: E402

LICENCE = "synthetic: generated by ClauseCheck, not a real document"
URL = "scripts/generate_synthetic.py"
FIXED_TIME = dt.datetime(2000, 1, 1)
N_CERTIFICATES = 30

DEFAULT_SUPPLIERS = [f"Synthetic Supplier {i:02d}" for i in range(1, 41)]
PRICE_HEADER = ["SKU", "Description", "Unit price", "Currency", "Payment terms"]
PARTS = [
    "Hex bolt M8",
    "Steel bracket",
    "Aluminium extrusion 2m",
    "Rubber gasket",
    "Control board v2",
    "Packaging carton",
    "Copper wire spool",
    "Bearing 6204",
    "Hydraulic hose",
    "Safety valve",
    "LED panel",
    "Cable harness",
    "Filter cartridge",
    "Pump seal kit",
    "Sensor module",
]
CURRENCIES = ["USD", "EUR", "GBP"]
PAYMENT_TERMS = ["Net 30", "Net 45", "Net 60", "Net 90", "2/10 Net 30"]
CERT_TYPES = ["ISO 27001", "SOC 2 Type II", "ISO 9001"]
ISSUERS = [
    "Northgate Certification Ltd",
    "Meridian Assurance Services",
    "Bluewater Standards Registrar",
    "Capstone Audit Partners",
]


def pick_key_suppliers(names: list[str], seed: int, n: int = 40) -> list[str]:
    """Return a seeded, sorted sample of `n` supplier names (all of them if fewer)."""
    ordered = sorted(set(names))
    if len(ordered) <= n:
        return ordered
    return sorted(random.Random(seed).sample(ordered, n))


def _iso(day: dt.date) -> str:
    return day.isoformat()


def _random_date(rng: random.Random, start_year: int, end_year: int) -> dt.date:
    start = dt.date(start_year, 1, 1)
    return start + dt.timedelta(days=rng.randrange((dt.date(end_year, 12, 28) - start).days))


def _plus_years(day: dt.date, years: int) -> dt.date:
    try:
        return day.replace(year=day.year + years)
    except ValueError:  # 29 February
        return day.replace(year=day.year + years, day=28)


def _relative(path: Path) -> str:
    try:
        return path.resolve().relative_to(ROOT).as_posix()
    except ValueError:  # outside the repo (tests): use the canonical location
        return f"data/raw/synthetic/{path.name}"


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _save_docx(document: "docx.document.Document", path: Path) -> None:
    """Save with fixed timestamps so the file bytes depend only on the content."""
    props = document.core_properties
    props.author = props.last_modified_by = "ClauseCheck"
    props.created = props.modified = FIXED_TIME
    buffer = io.BytesIO()
    document.save(buffer)
    buffer.seek(0)
    with zipfile.ZipFile(buffer) as zin, zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as zout:
        for info in zin.infolist():
            fixed = zipfile.ZipInfo(info.filename, date_time=(1980, 1, 1, 0, 0, 0))
            fixed.compress_type = zipfile.ZIP_DEFLATED
            fixed.external_attr = info.external_attr
            zout.writestr(fixed, zin.read(info.filename))


def _row(**fields: str) -> dict:
    base = dict.fromkeys(schema.MANIFEST_COLUMNS, "")
    base.update(
        source="synthetic",
        licence=LICENCE,
        url=URL,
        parent_doc_id="",
        is_synthetic="true",
    )
    base.update(fields)
    return {col: base[col] for col in schema.MANIFEST_COLUMNS}


def _price_schedule(rng: random.Random, n: int, name: str, out_dir: Path, truth: list) -> dict:
    title = f"Price Schedule {n}: {name}"
    did = doc_id("synthetic", title)
    effective = _random_date(rng, 2019, 2025)
    currency = rng.choice(CURRENCIES)
    terms = rng.choice(PAYMENT_TERMS)
    parts = rng.sample(PARTS, rng.randint(5, 15))

    document = docx.Document()
    document.add_paragraph(title)
    document.add_paragraph(f"Effective date: {_iso(effective)}")
    table = document.add_table(rows=1, cols=len(PRICE_HEADER))
    for cell, text in zip(table.rows[0].cells, PRICE_HEADER, strict=True):
        cell.text = text
    skus = []
    for i, part in enumerate(parts):
        sku = f"SKU-{rng.randint(1000, 9999)}-{i:02d}"
        price = f"{rng.randint(50, 50000) / 100:.2f}"
        skus.append((sku, price))
        cells = table.add_row().cells
        for cell, text in zip(cells, [sku, part, price, currency, terms], strict=True):
            cell.text = text

    path = out_dir / f"price_schedule_{n}.docx"
    _save_docx(document, path)

    truth.append({"doc_id": did, "field": "effective_date", "value": _iso(effective)})
    truth.append({"doc_id": did, "field": "payment_terms", "value": terms})
    for sku, price in rng.sample(skus, min(3, len(skus))):
        truth.append({"doc_id": did, "field": f"unit_price:{sku}", "value": f"{price} {currency}"})
    return _row(
        doc_id=did,
        supplier_id=schema.supplier_id_from_name(name),
        doc_type="price_schedule",
        format="docx",
        path=_relative(path),
        title=title,
        effective_date=_iso(effective),
        sha256=_sha256(path),
    )


def _certificate(rng: random.Random, n: int, name: str, out_dir: Path, truth: list) -> dict:
    title = f"Certificate {n}: {name}"
    did = doc_id("synthetic", title)
    cert_type = rng.choice(CERT_TYPES)
    issuer = rng.choice(ISSUERS)
    number = f"CERT-{rng.randint(100000, 999999)}"
    valid_from = _random_date(rng, 2020, 2026)
    valid_until = _plus_years(valid_from, 3)

    text = "\n".join(
        [
            f"CERTIFICATE OF COMPLIANCE: {cert_type}",
            f"Issuer: {issuer}",
            f"This certifies that {name} operates a management system that meets {cert_type}.",
            f"Certificate number: {number}",
            f"Valid from {_iso(valid_from)}",
            f"Valid until {_iso(valid_until)}",
            "",
        ]
    )
    path = out_dir / f"certificate_{n}.txt"
    path.write_text(text, encoding="utf-8", newline="\n")

    for field, value in [
        ("certificate_type", cert_type),
        ("issuer", issuer),
        ("supplier_name", name),
        ("certificate_number", number),
        ("valid_from", _iso(valid_from)),
        ("valid_until", _iso(valid_until)),
    ]:
        truth.append({"doc_id": did, "field": field, "value": value})
    return _row(
        doc_id=did,
        supplier_id=schema.supplier_id_from_name(name),
        doc_type="certificate",
        format="txt",
        path=_relative(path),
        title=title,
        effective_date=_iso(valid_from),
        sha256=_sha256(path),
    )


def generate(seed: int, out_dir: Path, suppliers: list[str] | None = None) -> list[dict]:
    """Write the synthetic files and `ground_truth.jsonl`; return their manifest rows.

    `suppliers` are display names. Each gets one price schedule, and the first
    `N_CERTIFICATES` (in a seeded shuffle) also get a certificate.
    """
    rng = random.Random(seed)
    names = list(suppliers) if suppliers else list(DEFAULT_SUPPLIERS)
    out_dir.mkdir(parents=True, exist_ok=True)
    truth: list[dict] = []
    rows = [_price_schedule(rng, n, name, out_dir, truth) for n, name in enumerate(names, 1)]
    certified = rng.sample(names, min(N_CERTIFICATES, len(names)))
    rows += [_certificate(rng, n, name, out_dir, truth) for n, name in enumerate(certified, 1)]

    with (out_dir / "ground_truth.jsonl").open("w", encoding="utf-8", newline="\n") as f:
        for fact in truth:
            f.write(json.dumps(fact, sort_keys=True) + "\n")
    return rows


def _suppliers_from_csv(path: Path, seed: int) -> list[str] | None:
    if not path.exists():
        return None
    with path.open(newline="", encoding="utf-8") as f:
        names = [r["display_name"] for r in csv.DictReader(f)]
    return pick_key_suppliers(names, seed) if names else None


def main(argv: list[str] | None = None) -> int:
    """Command line entry point."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--out", type=Path, default=Path("data/raw/synthetic"))
    args = parser.parse_args(argv)
    suppliers = _suppliers_from_csv(ROOT / "data" / "suppliers.csv", args.seed)
    rows = generate(args.seed, args.out, suppliers)
    print(f"wrote {len(rows)} documents to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
